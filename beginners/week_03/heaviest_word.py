# Задача: «Самое тяжёлое слово»
# Курс: «Поколение Python: курс для начинающих»
#
# Вес слова — это сумма Unicode-кодов всех его символов.
# Программа считывает четыре слова и находит слово
# с наибольшим весом. Если веса равны, остаётся первое слово.

# Переменная для хранения самого тяжёлого слова
answer = ''

# Максимальный вес среди уже обработанных слов
m = 0

# Считываем четыре слова
for i in range(4):
    summa = 0
    n = input()

    # Вычисляем вес слова
    for j in n:
        summa += ord(j)

    # Если вес больше максимального, обновляем результат
    if summa > m:
        answer = n
        m = summa

# Выводим самое тяжёлое слово
print(answer)