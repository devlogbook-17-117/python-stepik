# Задача: «Автомобильный номер»
# Курс: «Поколение Python: курс для начинающих»
#
# Программа проверяет, соответствует ли строка формату
# российского автомобильного номера.
#
# Допустимый формат:
# БУКВА + 3 ЦИФРЫ + 2 БУКВЫ + "_" + 2 ИЛИ 3 ЦИФРЫ
#
# Разрешённые буквы: АВЕКМНОРСТУХ

# Считываем номер
n = input()

# По умолчанию считаем номер некорректным
answer = 'NO'

# Проверяем первую букву и наличие символа "_"
if n[0].isalpha() and n[0] in 'АВЕКМНОРСТУХ' and n[6] == '_':
    # Проверяем три цифры после первой буквы
    if n[1:4].isdigit():
        # Проверяем две разрешённые буквы
        if n[4:6].isalpha() and n[4] in 'АВЕКМНОРСТУХ' and n[5] in 'АВЕКМНОРСТУХ':
            # Проверяем количество цифр в конце номера
            if (n[7:9].isdigit() and len(n) == 9) or (n[7:10].isdigit() and len(n) == 10):
                answer = 'YES'

# Выводим результат проверки
print(answer)