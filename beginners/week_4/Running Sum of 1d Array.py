class Solution:
    def runningSum(self, nums: list[int]) -> list[int]:
        # sp будет хранить накопленные суммы.
        sp = []

        # m — сумма элементов, обработанных на данный момент.
        m = nums[0]

        # Если в списке один элемент, накопленная сумма не меняется.
        if len(nums) == 1:
            return nums

        # Начинаем со второго элемента:
        # первый элемент уже сохранён в m.
        for i in range(len(nums) - 1):
            sp.append(m)

            # Добавляем следующий элемент к накопленной сумме.
            m += nums[i + 1]

        # Добавляем итоговую сумму последнего элемента.
        sp.append(m)

        return sp