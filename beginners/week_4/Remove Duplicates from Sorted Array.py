class Solution:
    def removeDuplicates(self, nums: list[int]) -> int:
        # Индекс текущего элемента, который сравниваем со следующим.
        i = 0

        # Идём до предпоследнего элемента.
        while i < len(nums) - 1:
            # В отсортированном списке дубликаты стоят рядом.
            if nums[i] == nums[i + 1]:
                # Удаляем повторяющийся элемент.
                # После удаления следующий элемент сдвигается на его место.
                del nums[i]
            else:
                # Если элементы разные, переходим к следующей паре.
                i += 1

        # Возвращаем количество уникальных элементов.
        return len(nums)