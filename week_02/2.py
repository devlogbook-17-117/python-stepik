# Задача: Чётные цифры

# Ввод числа и создание копий и служебных переменных[span_1](start_span)[span_1](end_span):
# n1, n2 - копии числа n для двух циклов
# i - счётчик для нумерации чётных цифр
# f - флаг (0 - чётных цифр пока нет, 1 - нашли хотя бы одну)
# s - строка для сборки развёрнутого числа
n = int(input())
n1, n2, i, f, s = n, n, 1, 0, ''

# Шаг 1: Разворачиваем число задом наперёд[span_2](start_span)[span_2](end_span)
# С помощью % 10 забираем цифры с конца и собираем их в строку s[span_3](start_span)[span_3](end_span)
while n1 != 0:
    d1 = n1 % 10
    s += str(d1)
    n1 //= 10

# Шаг 2: Переходим к развёрнутому числу[span_4](start_span)[span_4](end_span)
n = int(s)
while n2 != 0:
    d = n % 10
    
    # Проверяем цифру на чётность[span_5](start_span)[span_5](end_span)
    if d % 2 == 0:
        f = 1  # Переключаем флаг: чётная цифра найдена[span_6](start_span)[span_6](end_span)
        print(str(i) + '-я четная цифра равна', d)  # Выводим номер и значение[span_7](start_span)[span_7](end_span)
        i += 1  # Увеличиваем счётчик строго после вывода чётной цифры[span_8](start_span)[span_8](end_span)
        
    n //= 10
    n2 //= 10

# Шаг 3: Если флаг остался 0 — чётных цифр в числе не было вообще[span_9](start_span)[span_9](end_span)
if f == 0:
    print('Четных цифр в числе нет')