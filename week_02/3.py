# Задача: Ход слона

# Ввод координат первой и второй клетки шахматной доски
x1, y1 = int(input()), int(input())
x2, y2 = int(input()), int(input())

# Проверка диагоналей:
# Слон может сходить на клетку, если смещение по X равно смещению по Y
# x1 - x2 == y1 - y2     --> движение в одном направлении (например, вверх-вправо)
# x1 - x2 == -(y1 - y2)  --> движение в противоположном направлении (например, вверх-влево)
if x1 - x2 == y1 - y2 or x1 - x2 == -(y1 - y2):
    print('YES')
else:
    print('NO')